# 5) 버블 정렬 (Bubble Sort)
# [개념] 인접한 두 원소를 비교하여 정정 조건에 맞지 않으면 자리를 교환하는 정렬 방식
# - 특징: 매 회전(Pass)마다 가장 큰(또는 작은) 원소가 리스트의 끝으로 이동함 (거품이 올라오는 모양과 유사)
# - 성능: 최악과 평균의 경우 O(n^2)의 시간 복잡도를 가짐

# [2, 4, 5, 1, 3] 앞에서부터 두 개씩 대소 비교하며 정렬 수행
def bubble_sort(a):
    n = len(a)
    # [문법] while True: 무한 루프를 생성하며, 내부에서 return이나 break를 만날 때까지 반복
    while True:
        changed = False     # 자료 앞뒤 변경 여부 (Flag 변수: 이번 회전에서 교환이 일어났는지 체크)

        # [문법] range(0, n-1): 마지막 요소는 i+1로 접근하므로 인덱스 범위를 n-1까지로 제한
        for i in range(0, n-1):
            if a[i] > a[i+1]:   # 앞의 요소가 뒤의 요소보다 크면 (오름차순 조건)
                # print(a)      # 정렬 과정을 확인하기 위한 중간 출력
                # [문법] a[i], a[i+1] = a[i+1], a[i] : 파이썬의 튜플 언패킹을 이용한 Swap(값 교환)
                a[i], a[i+1] = a[i+1], a[i]
                changed = True  # 교환이 발생했음을 기록
        
        # [개념] 최적화: 한 번의 루프 동안 교환(changed)이 한 번도 없었다면 이미 정렬된 상태임
        if not changed:         # changed == False와 동일한 표현
            return              # 함수를 종료하고 호출한 곳으로 돌아감
                
d = [2, 4, 5, 1, 3]
bubble_sort(d)
print("최종 정렬 결과:", d)

# [추천] : 일반적인 버블 정렬은 매 회전마다 가장 큰 값이 끝으로 가므로, 
# 내부 루프의 범위를 range(0, n-1-j)와 같이 줄여나가는 방식이 더 효율적입니다.
# 또한, 데이터 양이 많을 경우 파이썬 내장 함수인 sorted(d)나 d.sort()를 사용하는 것이 성능상 훨씬 유리합니다.
