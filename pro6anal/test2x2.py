# 교차 분석 - 카이 제곱, 카이스퀘어 가설 검정
# 범주형 자료(변수)를 대상으로 교차빈도에 대한 기술 통계량을 제공
# 교차빈도에 대한 통계적 유의성을 검증해주는 분석 기법
# [개념] 카이제곱 분포: 분산이 퍼져 있는 모습을 분포로 만든 것. 정규분포를 따르는 여러 독립적인 변수들의 제곱합이 이루는 분포
# [공식] X² = ∑{(관측값 - 기대값)²/ 기대값}
# - 관측값(Observed): 실제 수집된 데이터의 빈도
# - 기대값(Expected): 두 변수가 서로 독립일 때 이론적으로 예상되는 빈도

# [분류]
# 1) 적합도 검정: 관찰된 빈도가 특정 이론적 분포를 따르는지 검정 (일원 카이제곱)
# 2) 독립성/동질성 검정: 두 범주형 변수 간의 연관성 유무를 검정 (이원 카이제곱)

###########################################################
# 가설을 채택하는 두 가지 방법 연습
###########################################################
import pandas as pd

#################
# 데이터 수집
#################
# [문법] pd.read_csv: CSV 파일을 읽어 데이터프레임으로 변환. encoding='euc-kr'은 한글 깨짐 방지
data = pd.read_csv('pass_cross.csv', encoding='euc-kr')
print(data.head())
print(data.shape)       # (행, 열) 크기 확인 -> (50, 4)
print(data.shape[0])    # 데이터의 개수(행의 수)
print(data.shape[1])    # 변수의 개수(열의 수)
print('\n')

#####################################
# 가설설정
#####################################
# 귀무가설(H0) : 벼락치기 공부하는 것과 합격 여부는 관계가 없다
# 대립가설(H1) : 벼락치기 공부하는 것과 합격 여부는 관계가 있다

# [문법] 불리언 인덱싱을 이용한 조건부 카운팅: & (AND) 연산자로 두 조건을 모두 만족하는 행 추출
print(data[(data['공부함'] == 1) & (data['합격'] == 1)].shape[0])
print(data[(data['공부함'] == 1) & (data['불합격'] == 1)].shape[0])
print('\n')

# 빈도표 작성
# [문법] pd.crosstab(index, columns): 두 범주형 변수의 교차 빈도표(Contingency Table) 생성
# margins=True: 행과 열의 합계(All)를 자동으로 계산하여 추가
ctab = pd.crosstab(index=data['공부안함'], columns=data['불합격'], margins=True)
ctab.columns = ['합격', '불합격', '합계']
ctab.index = ['공부함', '공부안함', '합계']
print(ctab)     # 관찰값(Observed Frequency) 출력
print('\n')

########################################################
# 검정 방법 1 : 카이제곱 표 사용해서 -> 임계값을 얻기 위해
########################################################

# 기대도수 = (각 행의 주변합) * (각 열의 주변합) / 총합(전체표본수)
# [개념] 기대값: 두 변수가 독립이라는 가정하에 계산된 이론적 빈도

# 카이제곱 값(수식에 따른 계산에 의해서)
# chi2 = 3.0
# [개념] 자유도(dof, Degrees of Freedom): (행의 수 - 1) * (열의 수 - 1)
# dof = (2 - 1) * (2 - 1) = 1
# 유의수준 = 0.05
# 임계값 = 3.84
# 판정 : 카이제곱 검정 통계량(3) < 임계값(3.84) 이므로, 귀무 채택 영역 내 존재 => 귀무 가설 채택!
#      : 그러므로 벼락치기 공부하는 것과 합격여부는 관계 없다는 의견 유지

#######################################
# 검정 방법 2 : p-value 사용
#######################################
import scipy.stats as stats
# [문법] stats.chi2_contingency(observed): 교차표를 입력받아 카이제곱 통계량, p-value, 자유도, 기대빈도를 반환
chi2, p, dof, expected = stats.chi2_contingency(ctab)
print(chi2, p, dof, expected)

# chi2 = 3.0
# p = 0.5578254003710748
# dof = 4
# [개념] p-value(유의확률): 귀무가설이 맞다는 전제하에, 현재와 같은 결과가 나타날 확률
# 판정 : 유의 수준 0.05 < p(0.557825) 이므로, 귀무 가설 채택(H0 채택)
# 결론 : 검정에 사용된 자료는 우연히 발생한 자료라고 할 수 있으며, 두 변수 간 유의미한 관계가 없음.

# 카이제곱 검정 정식 명칭 : Pearson's chi-square Test
# 두 개의 불연속 변수(범주형) 간의 상관 관계 측정
# 관찰 빈도가 통계적으로 유의한지 확인

# [추천] : 실제 분석 시에는 margins=True가 포함된 표를 chi2_contingency에 넣으면 자유도가 왜곡될 수 있으므로, 
# 합계 열을 제외한 순수 빈도 데이터만 입력하는 것이 정확합니다. (예: stats.chi2_contingency(ctab.iloc[:2, :2]))