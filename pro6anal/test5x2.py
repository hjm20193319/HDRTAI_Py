# 독립성 검정 : 실습 2
# : 남성과 여성의 스포츠 음료 선호도 검정 (이원 카이제곱 - 독립성 검정)

# 귀무가설(H0) : 성별과 음료 선호는 서로 관련 없다.
# 대립가설(H1) : 성별과 음료 선호는 서로 관련이 있다.
# 독립변수 : 성별 / 종속변수 : 음료 선호도

#################
# 데이터 수집
#################
# [문법] pd.DataFrame: 딕셔너리 형태의 데이터를 데이터프레임으로 변환. key는 컬럼명, value는 리스트 형태의 데이터
data = pd.DataFrame({
    '게토레이':[30, 20],
    '포카리':[20, 30],
    '비타500':[10, 30]
}, index=['남성', '여성'])
print(data)     # [개념] 이미 집계된 형태의 데이터이므로 pd.crosstab()을 통한 빈도 계산 과정이 생략 가능함

# [문법] stats.chi2_contingency(data): 
# - chi2: 카이제곱 통계량 (관측값과 기대값의 차이의 제곱합을 기대값으로 나눈 것)
# - p: p-value (유의확률, 0.05보다 작으면 변수 간 연관성이 있다고 판단)
# - dof: 자유도 ( (행의수-1) * (열의수-1) = (2-1) * (3-1) = 2 )
chi2, p, dof, expected = stats.chi2_contingency(data)
print(f'chi2 : {chi2}, p : {p}, dof : {dof}')
print(f'기대도수 : \n', expected)

# 관측값
# 남성    30   20     10
# 여성    20   30     30
# 기대도수
# 21.42857143 21.42857143 17.14285714
# 28.57142857 28.57142857 22.85714286

