# 이원 카이제곱 검정 - 교차 분할표 이용
# : 두 개 이상의 변인(집단 또는 범주)을 대상으로 검정을 수행한다.
# 분석대상의 집단 수에 의해서 독립성 검정과 동질성 검정으로 나뉜다.
# [개념] 이원 카이제곱(Two-way Chi-square): 행과 열로 구성된 교차표를 통해 두 범주형 변수 간의 연관성을 분석함.

# 독립성(관련성) 검정
# - 동일 집단의 두 변인(학력수준과 대학진학 여부)을 대상으로 관련성이 있는가 없는가?
# - 독립성 검정은 두 변수 사이의 연관성을 검정한다

# 실습 1 : 교육수준과 흡연율 간의 관련성 분석 : smoke.csv
# [변수 설정] 독립 변수(원인): 교육수준 / 종속 변수(결과): 흡연율

import pandas as pd
import scipy.stats as stats

#################
# 가설 수립
#################
# 귀무가설 : 교육 수준과 흡연율 간에 관계가 없다. (독립이다, 연관성이 없다)
# 대립가설 : 교육 수준과 흡연율 간에 관계가 있다. (독립이 아니다, 종속적이다, 연관성이 있다)

#################
# 데이터 수집
################
# [문법] pd.read_csv: 외부 URL의 CSV 데이터를 읽어와 데이터프레임 생성
data = pd.read_csv('https://raw.githubusercontent.com/pykwon/python/refs/heads/master/testdata_utf8/smoke.csv')
print(data.head(3))
# [문법] .unique(): 컬럼 내 중복되지 않는 고유값들을 반환하여 범주 구성 확인
print(data['education'].unique())   # [1 : 대학원졸, 2 : 대졸, 3 : 고졸]
print(data['smoking'].unique())      # [1 : 과흡연, 2 : 보통, 3 : 비흡연]
print('\n')

# 학력 수준별 흡연 빈도수(교차표 사용)
# [문법] pd.crosstab(index, columns): 두 범주형 변수의 빈도를 집계하여 교차표(Contingency Table) 생성
ctab = pd.crosstab(index=data['education'], columns=data['smoking'])    # 관측 빈도 수
# [참고] normalize=True 옵션을 주면 빈도가 아닌 전체 대비 비율(0~1)로 출력됨
ctab.columns = ['과흡연', '보통', '비흡연']
ctab.index = ['대학원졸', '대졸', '고졸']
print(ctab)
print('\n')

# [추천] : 시각화를 위해 sns.heatmap(ctab, annot=True, fmt='d')를 사용하면 교육수준별 흡연 패턴을 한눈에 파악하기 좋습니다.

#########################
# 이원 카이제곱 검정
#########################
# [문법] stats.chi2_contingency(observed): 교차표를 입력받아 카이제곱 통계량, p-value, 자유도, 기대빈도를 반환
chi_result = [ctab.loc['대학원졸'], ctab.loc['대졸'], ctab.loc['고졸']]
chi2, p, dof, expected = stats.chi2_contingency(chi_result)
# [추천] : ctab 자체가 이미 데이터프레임 형태이므로 stats.chi2_contingency(ctab)로 직접 전달하는 것이 더 간결합니다.
print(f'chi2 : {chi2}, p : {p}, dof : {dof}')
# chi2 : 18.9109, p : 0.000818257, dof : 4
print(f'expected : \n', expected)   # 에측된 기대도수
print('\n')

##########################
# 판정 1
##########################
# 유의 수준 0.05 > p-value : 0.000818257 이므로, 귀무가설이 기각
# 결과 : 교육 수준과 흡연율 간에 유의미한 관계가 있다. 수집자료는 우연히 발생된 자료가 아니다.
# 어떤 대상이 흡연율이 높은지, 어떻게 활용할 것인지, 흡연율 줄이기 위해 어떤 방안을 낼 것인지 등의
# 의견을 토대로 보고서를 작성해야한다


########################
# 판정 2
########################
# [개념] 임계값(Critical Value) 비교: 계산된 통계량이 특정 자유도와 유의수준에서의 임계값보다 크면 귀무가설 기각
# [문법] stats.chi2.ppf(q=0.95, df=4): 유의수준 0.05에 해당하는 카이제곱 임계값(약 9.488)을 구하는 함수
# chi2(18.9109) > critical value(9.488, dof:4, alpha:0.05)
# chi2 값이 임계치 우측, 귀무 기각 영역에 있으므로, 귀무가설이 기각되고, 대립가설이 채택 됨
# [결론] 교육 수준에 따라 흡연 습관에 차이가 있다고 볼 수 있음 (독립이 아님).

