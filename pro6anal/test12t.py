############
# 가설 수립
############
# 귀무 가설(H0) : 특강 전후의 시험 점수는 차이가 없다. (평균의 차이가 0이다)
# 대립 가설(H1) : 특강 전후의 시험 점수는 차이가 있다. (평균의 차이가 0이 아니다)

import numpy as np
import pandas as pd
import scipy.stats as stats
import matplotlib.pyplot as plt
import koreanize_matplotlib
import seaborn as sns

################
# 데이터 수집
################
# [문법] np.random.seed: 난수 생성 시드를 고정하여 코드 실행 시마다 동일한 결과를 보장함
np.random.seed(123) 
# [문법] np.random.normal(loc, scale, size): 평균(loc), 표준편차(scale), 개수(size)를 지정하여 정규분포 난수 생성
x1 = np.random.normal(75, 10, 100) # 특강 전 점수
x2 = np.random.normal(80, 10, 100) # 특강 후 점수

################
# 정규성 확인
################
# [문법] sns.displot: 데이터의 분포를 히스토그램과 커널 밀도 추정(KDE) 곡선으로 시각화함
sns.displot(x1, kde=True)
sns.displot(x2, kde=True)
plt.show()

# [문법] stats.shapiro(data): 샤피로-윌크 검정을 통해 데이터가 정규분포를 따르는지 확인 (H0: 정규분포를 따른다)
print(stats.shapiro(x1).pvalue)    # 0.27487044002059957
print(stats.shapiro(x2).pvalue)    # 0.10214157305396582
# 0.05 보다 크므로, 정규성 만족
# [판정] 두 집단 모두 p-value > 0.05 이므로 귀무가설을 채택하여 정규성 가정을 충족함.
# [추천] : 대응 표본 t-검정에서는 각 집단의 정규성보다 '두 값의 차이(x2 - x1)'에 대한 정규성 검정이 더 권장됩니다.

#######################
# 대응 표본 t 검정
#######################
# [문법] stats.ttest_rel(a, b): 동일 집단의 전(a), 후(b) 데이터를 비교하는 대응 표본 t-검정 수행
print(stats.ttest_rel(x1, x2))
# T=-3.003102708378836, pvalue=0.00338, df=99
# [개념] 자유도(df): 표본 수(n) - 1 = 100 - 1 = 99
# [판정] 유의 수준 0.05 > p-value 0.0033 이므로, 귀무 가설 기각
# 결론 : 특강 전후의 시험 점수는 차이가 있다(특강이 시험 점수에 영향을 주었다)

# [추천] : 시각적으로 전후 변화를 보여주기 위해 plt.boxplot([x1, x2]) 또는 두 평균의 차이를 나타내는 막대 그래프를 활용할 수 있습니다.